def add(x, y):
    """Adds two numbers and returns the result."""
    return x + y

def subtract(x, y):
    """Subtracts two numbers and returns the result."""
    return x - y
# we are adding new function

def multiply(x, y):
    """Multiplies two numbers and returns the result."""
    return x * y

def divide(a, b):
    return a / b

# New feature: Power function
def power(a, b):
    return a ** b